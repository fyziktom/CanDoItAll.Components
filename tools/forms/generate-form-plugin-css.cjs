const fs = require("node:fs");
const path = require("node:path");
const { execFileSync } = require("node:child_process");

const repoRoot = path.resolve(__dirname, "..", "..");
const tailwindDir = path.join(repoRoot, "Tailwind");
const fixturePath = path.join(__dirname, "fixture.html");
const outputPath = path.join(tailwindDir, "forms", "form-plugin.generated.css");
const tempInputPath = path.join(tailwindDir, ".tmp-form-plugin-input.css");
const tempOutputPath = path.join(tailwindDir, ".tmp-form-plugin-output.css");

// Classes this repo's Forms components actually render (kept in sync with fixture.html).
// Add both here and to fixture.html together if a component starts using another
// @tailwindcss/forms class (e.g. form-textarea, form-radio).
const pluginClasses = ["form-input", "form-select", "form-checkbox"];

const header = `/*
  Generated by \`npm run generate:forms\` (tools/forms/generate-form-plugin-css.cjs).
  Do not edit by hand -- edit tools/forms/fixture.html or the plugin version instead,
  then regenerate.

  This bakes @tailwindcss/forms' (class strategy) compiled output into a checked-in,
  @layer components-wrapped file instead of registering the plugin live via @plugin.
  @tailwindcss/forms emits these rules unlayered, which would otherwise beat any
  consumer's Class="..." utility override on the components that use them (unlayered
  CSS always wins over @layer content, regardless of source order). Wrapping the
  static, build-time-resolved output in @layer components here keeps those overrides
  working, while Tailwind/forms/form-controls.css's .ui-input/.ui-select/.ui-checkbox
  (also @layer components, imported after this file) still win over these defaults.
 */
`;

function buildTailwindEntry() {
  const relativeFixture = path
    .relative(tailwindDir, fixturePath)
    .replaceAll("\\", "/");

  return `@layer theme, base, components, utilities;
@import "tailwindcss/theme.css" layer(theme);
@import "tailwindcss/preflight.css" layer(base);

@tailwind utilities;

@plugin "@tailwindcss/forms" {
  strategy: "class";
}

@source "${relativeFixture}";
`;
}

function extractRule(css, selector) {
  const needle = `.${selector} {`;
  const start = css.indexOf(needle);
  if (start === -1) {
    throw new Error(
      `@tailwindcss/forms did not emit '.${selector}' -- check tools/forms/fixture.html and the plugin version.`
    );
  }

  let depth = 0;
  let end = start;
  for (let i = start; i < css.length; i += 1) {
    if (css[i] === "{") depth += 1;
    if (css[i] === "}") {
      depth -= 1;
      if (depth === 0) {
        end = i + 1;
        break;
      }
    }
  }

  return css.slice(start, end).trimEnd();
}

function main() {
  fs.writeFileSync(tempInputPath, buildTailwindEntry(), "utf8");

  try {
    execFileSync(
      path.join(tailwindDir, "node_modules", ".bin", "tailwindcss"),
      ["-i", path.basename(tempInputPath), "-o", path.basename(tempOutputPath)],
      { cwd: tailwindDir, stdio: "pipe" }
    );

    const compiled = fs.readFileSync(tempOutputPath, "utf8");
    const rules = pluginClasses.map(selector => extractRule(compiled, selector));

    const body = rules.join("\n\n");
    const wrapped = `${header}\n@layer components {\n${body
      .split("\n")
      .map(line => (line.length > 0 ? `  ${line}` : line))
      .join("\n")}\n}\n`;

    fs.writeFileSync(outputPath, wrapped, "utf8");
    console.log(`Wrote ${path.relative(repoRoot, outputPath)}`);
  } finally {
    fs.rmSync(tempInputPath, { force: true });
    fs.rmSync(tempOutputPath, { force: true });
  }
}

main();
